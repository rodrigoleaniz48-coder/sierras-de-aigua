do $$ begin create policy lluvias_write on public.lluvias for all using (public.rol_actual() in ('admin','campo')) with check (public.rol_actual() in ('admin','campo')); exception when duplicate_object then null; end $$;
do $$ begin create policy informes_read  on public.informes_tecnicos for select using (auth.uid() is not null); exception when duplicate_object then null; end $$;
do $$ begin create policy informes_write on public.informes_tecnicos for all using (public.rol_actual() in ('admin','campo')) with check (public.rol_actual() in ('admin','campo')); exception when duplicate_object then null; end $$;

