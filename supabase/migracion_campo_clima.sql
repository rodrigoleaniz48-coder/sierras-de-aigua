-- =========================================================================
-- Clima (solo lluvia) e informes tecnicos del modulo Campo.
--   lluvias: dia + mm. Se integra al cronograma de 'Manejo de cultivo'.
--   informes_tecnicos: visitas del tecnico del predio (Marcelo Cabrera).
-- Lectura: todo usuario autenticado. Escritura: admin + campo.
-- =========================================================================
create table if not exists public.lluvias (
  id bigserial primary key,
  fecha date not null,
  mm numeric(6,1) not null,
  nota text,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);
create index if not exists idx_lluvias_fecha on public.lluvias(fecha);

create table if not exists public.informes_tecnicos (
  id bigserial primary key,
  fecha date not null,
  tecnico text not null,
  notas text,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);
create index if not exists idx_informes_fecha on public.informes_tecnicos(fecha);

alter table public.lluvias            enable row level security;
alter table public.informes_tecnicos  enable row level security;

